#!/usr/bin/env python3
"""generate the kernel symbol table from `nm -n kernel.elf` output.

reads nm output on stdin and writes a C file defining ksym_count,
ksym_table and ksym_names (see src/kernel/debug/ksyms.h), all placed in the
.ksyms section. empty stdin gives an empty table (the first link pass).

the kernel is linked twice: once with an empty table to learn the function
addresses, then again with the real table. .ksyms sits after .text, so the
table's size never moves a function. --check FILE re-generates from the final
kernel and fails if the result differs, which would mean that assumption broke.
"""

import argparse
import sys

# nm types for code: local/global text and weak symbols.
TEXT_TYPES = {"t", "T", "W"}


def is_marker(name):
    # linker-script markers (kernel_start, __text_end, __start_ktests, ...)
    # share addresses with real functions and would shadow them.
    return name.startswith("__") or name in ("kernel_start", "kernel_end")


def parse(lines):
    symbols = []
    seen = set()
    for line in lines:
        parts = line.split()
        if len(parts) != 3:
            continue
        addr_text, kind, name = parts
        if kind not in TEXT_TYPES or is_marker(name):
            continue
        addr = int(addr_text, 16)
        # keep one name per address; nm -n lists them in a stable order.
        if addr in seen:
            continue
        seen.add(addr)
        symbols.append((addr, name))
    symbols.sort()
    return symbols


def c_escape(name):
    return name.replace("\\", "\\\\").replace('"', '\\"')


def render(symbols):
    out = []
    out.append("// generated by tools/gen_ksyms.py from nm output. do not edit.")
    out.append('#include "kernel/debug/ksyms.h"')
    out.append("")
    out.append('#define KSYMS __attribute__((section(".ksyms"), used))')
    out.append("")
    out.append("KSYMS const uint32_t ksym_count = %du;" % len(symbols))
    out.append("")
    out.append("KSYMS const ksym_t ksym_table[] = {")
    offset = 0
    for addr, name in symbols:
        out.append("    {0x%08xul, %du}," % (addr, offset))
        offset += len(name) + 1
    if not symbols:
        out.append("    {0u, 0u},")
    out.append("};")
    out.append("")
    # the names in assembly (.ascii), not as a C string: gcc 16 can write
    # long string data with the .base64 directive, which older binutils
    # (the i686-elf toolchain) do not know
    out.append("__asm__(\".pushsection .ksyms, \\\"a\\\"\\n\"")
    out.append("        \".globl ksym_names\\n\"")
    out.append("        \"ksym_names:\\n\"")
    for _, name in symbols:
        out.append("        \".asciz \\\"%s\\\"\\n\"" % c_escape(name))
    out.append("        \".byte 0\\n\"")
    out.append("        \".popsection\");")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("-o", "--output", help="write the C file here")
    group.add_argument("--check", help="compare against this generated file")
    args = parser.parse_args()

    text = render(parse(sys.stdin))

    if args.check:
        with open(args.check) as f:
            if f.read() != text:
                sys.stderr.write(
                    "gen_ksyms: function addresses moved between link passes\n")
                return 1
        return 0

    with open(args.output, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
