; src/arch/x86/asm64/isr.asm
; the x86_64 interrupt stubs and the common handler.
;
; in long mode the CPU always pushes ss, rsp, rflags, cs and rip, and it
; aligns RSP to 16 bytes first. a stub pushes an error code (if the CPU did
; not) and the vector number; isr_common pushes the general registers. the
; result is a struct registers (cpu/isr.h): 22 words, so RSP stays aligned
; to 16 bytes for the call into C.

BITS 64

extern isr_handler

; for interrupts that do NOT push an error code: push a zero one, so the
; frame is the same for all vectors
%macro ISR_NOERRORCODE 1

global isr_stub_%1
isr_stub_%1:
    push qword 0
    push qword %1
    jmp isr_common

%endmacro

; for interrupts that DO push an error code
%macro ISR_ERRORCODE 1

global isr_stub_%1
isr_stub_%1:
    push qword %1
    jmp isr_common

%endmacro

; the stubs for all 256 vectors (generated by tools/generate_isrs.sh)
%include "isr_gen.inc"

; the syscall entry (syscall.asm) also comes here, with the same frame
global isr_common
isr_common:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15

    cld
    mov rdi, rsp                ; isr_handler(struct registers *)
    call isr_handler

; the return half of isr_common. a forked child starts here, with RSP at a
; copy of its parent's saved registers (arch_setup_fork_stack).
global isr_exit
isr_exit:
    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    add rsp, 16                 ; the vector number and the error code
    iretq
